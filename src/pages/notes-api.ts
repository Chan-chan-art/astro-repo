import type { APIRoute } from 'astro';
import { pool } from '../lib/db';

export const prerender = false;

// Helper to capture verified operational User ID from session data context safely
async function getUserIdFromSession(cookies: any): Promise<number | null> {
  const sessionCookie = cookies.get("user_session");
  const sessionData = sessionCookie ? sessionCookie.json() : null;
  if (!sessionData || !sessionData.username) return null;

  const [rows]: any = await pool.execute('SELECT id FROM users WHERE BINARY username = ?', [sessionData.username]);
  return rows.length === 1 ? rows[0].id : null;
}

// 1. POST HANDLER - Append New Notes
export const POST: APIRoute = async ({ request, cookies }) => {
  try {
    const userId = await getUserIdFromSession(cookies);
    if (!userId) {
      return new Response(JSON.stringify({ success: false, message: "Unauthorized" }), { status: 401 });
    }

    const formData = await request.formData();
    const title = formData.get("title")?.toString().trim() || "";
    const content = formData.get("content")?.toString().trim() || "";

    if (!title || !content) {
      return new Response(JSON.stringify({ success: false, message: "Title and body contexts are required fields" }), { status: 400 });
    }

    // 1. Insert the new note record row into MySQL
    const [result]: any = await pool.execute(
      'INSERT INTO notes (user_id, title, content) VALUES (?, ?, ?)', 
      [userId, title, content]
    );

    // 2. Grab the auto-incremented primary ID number generated by MySQL
    const newInsertedId = result.insertId;

    // 3. Return the response payload INSIDE the function scope body cleanly
    return new Response(
      JSON.stringify({ 
        success: true, 
        id: newInsertedId,
        date: "Just now"
      }), 
      { status: 200 }
    );
  } catch (err) {
    console.error("Database note creation fault:", err);
    return new Response(JSON.stringify({ success: false, message: "Database creation fault" }), { status: 500 });
  }
};

// 2. DELETE HANDLER - Safely Remove Personal Notes
export const DELETE: APIRoute = async ({ url, cookies }) => {
  try {
    const userId = await getUserIdFromSession(cookies);
    if (!userId) {
      return new Response(JSON.stringify({ success: false, message: "Unauthorized session access parameters." }), { status: 401 });
    }

    const noteId = url.searchParams.get("id");
    if (!noteId) {
      return new Response(JSON.stringify({ success: false, message: "Missing resource routing identifier." }), { status: 400 });
    }

    // Validate scope ownership conditions before dropping rows to ensure privacy
    await pool.execute('DELETE FROM notes WHERE id = ? AND user_id = ?', [noteId, userId]);
    return new Response(JSON.stringify({ success: true }), { status: 200 });
  } catch (err) {
    console.error("Database deletion error track:", err);
    return new Response(JSON.stringify({ success: false, message: "Database deletion fault." }), { status: 500 });
  }
};
